// Лабораторна робота № 5. Завдання 5.5. Рекурсивні функції. Варіант 30
// Задача: по колу стоять n людей (номери 1..n), кожна друга людина виходить
// з кола, доки не залишиться одна. Процедура повторюється для x людей, де x -
// номер тієї, що залишилась, доки x не стане рівним кількості людей у раунді.
#include <iostream>
using namespace std;
 
// Номер людини, яка залишиться в колі з n людей (кожна друга виходить).
// Рекурентне співвідношення:
//   f(1) = 1;
//   f(n) = 2*f(n/2) - 1, якщо n - парне;
//   f(n) = 2*f(n/2) + 1, якщо n - непарне.
// n     - кількість людей (параметр-значення)
// level - поточний рівень рекурсії (параметр-значення)
// depth - глибина рекурсії (параметр-посилання)
int survivor(int n, int level, int &depth)
{
   if (level > depth)                   // оновлюємо глибину рекурсії
       depth = level;
   cout << "      level = " << level << ", n = " << n << endl;
 
   if (n == 1)                          // базова задача, вихід з рекурсії
       return 1;
 
   int x = survivor(n / 2, level + 1, depth);   // рекурсивний спуск
 
   if (n % 2 == 0)                      // дії на рекурсивному підйомі
       return 2 * x - 1;
   else
       return 2 * x + 1;
}
 
// Повторює процедуру виходу людей з кола, доки номер людини, що залишилась,
// не стане рівним кількості людей у поточному раунді.
// n       - кількість людей у поточному раунді (параметр-значення)
// level   - номер раунду = рівень рекурсії (параметр-значення)
// repeats - кількість повторень процедури після першої ітерації (параметр-посилання)
// depth   - глибина рекурсії (параметр-посилання)
// Результат - номер людини, яка залишилась.
int finalPerson(int n, int level, int &repeats, int &depth)
{
   if (level > depth)                   // оновлюємо глибину рекурсії
       depth = level;
   if (level > 1)                       // кожен раунд, крім першого, - повторення
       repeats++;
   cout << "Раунд (level) = " << level << ": у колі " << n << " людей" << endl;
 
   int innerDepth = 0;                  // глибина рекурсії функції survivor
   int x = survivor(n, 1, innerDepth);
   cout << "   залишилась людина № " << x
        << ", глибина рекурсії survivor = " << innerDepth << endl;
 
   if (x == n)                          // умова закінчення, базова задача
       return x;
 
   return finalPerson(x, level + 1, repeats, depth);   // наступний раунд
}
 
int main()
{
   int n;
   do
   {
       cout << "n = ";
       cin >> n;
   } while (n < 1);                     // кількість людей має бути натуральною
 
   int repeats = 0;                     // кількість повторень після першої ітерації
   int depth = 0;                       // глибина рекурсії функції finalPerson
 
   int y = finalPerson(n, 1, repeats, depth);
 
   cout << endl;
   cout << "Залишилась людина № " << y << endl;
   cout << "Кількість повторень після першої ітерації = " << repeats << endl;
   cout << "Глибина рекурсії finalPerson = " << depth << endl;
   return 0;
}